function run(sc) {
  const w = new World(sc.H, sc.platforms);
  const b = w.blocks.find((q) => sc.start.x + 48 >= q.start && sc.start.x + 48 < q.end);
  const s = standingAt(sc.start.x, b.top);
  let fell = false;
  for (const f of sc.frames) if (step(w, s, f.h, f.jump, real)) { fell = true; break; }
  return { x: +s.x.toFixed(3), y: +s.y.toFixed(3), onGround: s.ground, fell };
}

function fixture() {
  return {
    note: 'Generated by tools/levelgen/parity.js. Do not edit.',
    tile: T.TILE,
    scenarios: scenarios.map((sc) => ({
      name: sc.name,
      // columns as [start, end, top] for ground, in world units
      ground: T.blocksOf(sc.H).map((q) => [q.start, q.end, q.top]),
      platforms: sc.platforms.map((p) => [p.x, p.x + p.width, p.y]),
      start: sc.start,
      frames: sc.frames.map((f) => [f.h, f.jump ? 1 : 0]),
      expect: run(sc),
    })),
  };
}

if (require.main === module) {
  fs.writeFileSync(FILE, JSON.stringify(fixture(), null, 1) + '\n');
  const f = fixture();
  for (const s of f.scenarios) console.log(s.name.padEnd(74), JSON.stringify(s.expect));
  console.log('wrote', FILE);
}
module.exports = { fixture, scenarios, FILE };
