#!/usr/bin/env node
'use strict';
// For every level on disk, one winning run with the real jump physics: the exact
// stick position and jump press of every frame, from the start to the end gate.
// Written to test/fixtures/level_paths.json, which test/game/level_playthrough_test.dart
// replays through the game's own PlayerComponent on the loaded level. If the
// game and the generator ever disagree about the ground, a run falls off the
// map and that test says which level.
//
//   node tools/levelgen/paths.js
const fs = require('fs');
const path = require('path');
const tmx = require('./tmx');
const { solve, runLength } = require('./solve');
const { real } = require('./sim');

const DIR = path.join(__dirname, '..', '..', 'assets', 'tiles', 'levels');
const FILE = path.join(__dirname, '..', '..', 'test', 'fixtures', 'level_paths.json');

function build() {
  const out = { note: 'Generated by tools/levelgen/paths.js. Do not edit. Frames are [stick, jump, count] at 60 fps.', levels: {} };
  const files = fs.readdirSync(DIR).filter((f) => /^era\d+_\d+\.tmx$/.test(f)).sort((a, b) => {
    const [ea, la] = a.match(/\d+/g).map(Number);
    const [eb, lb] = b.match(/\d+/g).map(Number);
    return ea - eb || la - lb;
  });
  for (const f of files) {
    const level = tmx.read(fs.readFileSync(path.join(DIR, f), 'utf8'));
    // The widest margin that still leaves a winning run.
    let r = null;
    for (const margin of [8, 5, 3, 0]) {
      r = solve(level, { phys: real, wantPath: true, margin });
      if (r.reachable) break;
    }
    if (!r.reachable) throw new Error(`${f}: no winning run with the real physics`);
    out.levels[f.replace('.tmx', '')] = {
      goalX: (level.gates[0] ?? level.exitX) - 150,
      frames: runLength(r.frames),
    };
  }
  return out;
}

if (require.main === module) {
  const t0 = Date.now();
  const data = build();
  fs.writeFileSync(FILE, JSON.stringify(data) + '\n');
  const n = Object.keys(data.levels).length;
  const frames = Object.values(data.levels).reduce((s, l) => s + l.frames.reduce((a, f) => a + f[2], 0), 0);
  console.log(`wrote ${FILE}: ${n} levels, ${frames} frames, ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}
module.exports = { build, FILE };
