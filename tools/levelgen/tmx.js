'use strict';
// Writes a level model as a Tiled .tmx, and reads one back (generated or
// hand-built) into the same shape so the validator can check either.
//
// The `ground` layer holds the finished terrain: every cell already carries the
// right cap, edge, wall or fill tile (terrain.js), so the map looks complete in
// Tiled and the game just draws the layer. A column with no tiles is a pit. The
// `entities` object layer holds everything that is not ground.
const { physics, rules, eras, eraNumber } = require('./rules');
const T = require('./terrain');

const TILE = T.TILE;
const ROWS = T.ROWS;

// ── write ───────────────────────────────────────────────────────────────────
function write(level) {
  const era = eras[eraNumber(level.props.era) - 1];
  const cols = level.H.length;
  const theme = T.ERA_THEME[level.props.era];
  const grid = T.autotile(level.H, level.S, theme, level.C);
  const rows = grid.map((r) => r.join(','));

  let id = 1;
  const objects = [];
  const add = (xml) => objects.push('  ' + xml);
  add(`<object id="${id++}" name="start" type="spawn" x="${level.spawnX}" y="${physics.groundSurfaceY}"/>`);

  const items = [
    ...level.coins.map((o) => ({ x: o.x, xml: (i) => `<object id="${i}" type="coin" x="${o.x}" y="${o.y}"/>` })),
    ...level.artifacts.map((o) => ({
      x: o.x,
      xml: (i) =>
        `<object id="${i}" type="artifact" x="${o.x}" y="${o.y ?? physics.groundSurfaceY}">\n` +
        `   <properties>\n    <property name="art" value="${o.art}"/>\n   </properties>\n  </object>`,
    })),
    ...level.enemies.map((o) => ({
      x: o.x,
      xml: (i) =>
        `<object id="${i}" type="enemy" x="${o.x}" y="${o.y ?? physics.groundSurfaceY}">\n` +
        `   <properties>\n    <property name="kind" value="${o.kind}"/>\n` +
        `    <property name="behavior" value="${o.behavior}"/>\n` +
        `    <property name="patrol" type="float" value="${o.patrol}"/>\n   </properties>\n  </object>`,
    })),
    ...level.platforms.map((o) => ({
      x: o.x,
      xml: (i) => `<object id="${i}" type="platform" x="${o.x}" y="${o.y}" width="${o.width}" height="${physics.platformTile}"/>`,
    })),
  ].sort((a, b) => a.x - b.x);
  for (const it of items) add(it.xml(id++));
  if (level.arena) {
    // A boss arena has no gate and no exit: the level ends when the boss is beaten.
    add(`<object id="${id++}" name="boss" type="boss" x="${level.arena.boss.x}" y="${level.arena.boss.y}"/>`);
    for (const x of level.arena.minions) add(`<object id="${id++}" type="minion_spawn" x="${x.x}" y="${x.y}"/>`);
  } else {
    for (const gx of level.gates) add(`<object id="${id++}" type="gate" x="${gx}" y="${physics.groundSurfaceY}"/>`);
    add(`<object id="${id++}" name="finish" type="exit" x="${level.exitX}" y="${physics.groundSurfaceY}"/>`);
  }

  const p = level.props;
  const props = [
    `  <property name="era" value="${p.era}"/>`,
    `  <property name="level" type="int" value="${p.level}"/>`,
    `  <property name="grade" type="int" value="${era.grade}"/>`,
    `  <property name="term" type="int" value="${era.term}"/>`,
    `  <property name="weeks" value="${era.levelWeeks[p.level - 1].join(',')}"/>`,
  ];
  if (p.level <= 2) props.push(`  <property name="kaalamanStart" type="int" value="1"/>`);
  if (level.arena) props.push(`  <property name="boss" type="bool" value="true"/>`);
  props.push(`  <property name="generator" value="${level.arena ? 'arena-v1' : rules.generatorId}"/>`);
  props.push(`  <property name="seed" value="${level.seed}"/>`);

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  era${eraNumber(p.era)}_${p.level}.tmx — generated by tools/levelgen (${rules.generatorId}), seed ${level.seed}.
  ${level.arena ? 'Boss arena: one fixed room, authored in arenas.js.' : level.opener ? 'Era opener: a hand-authored sequence of set pieces (see openers.js).' : 'Difficulty scalar d = ' + level.d.toFixed(2) + ' across the era.'}
  Regenerate: ${level.arena ? 'node tools/levelgen/arenas.js' : 'run tools/levelgen/generate.js with era ' + p.era + ' and level ' + p.level + '.'}
  To keep a hand edit, set the map property handEdited to true; the generator
  then refuses to overwrite this file unless forced.
  Ground: one tile column per 16 units; the top tile of a column is its surface, a
  column with no tiles is a pit. Row ${T.BASE_ROW} is the base ground (y ${physics.groundSurfaceY}); the layer is
  drawn ${T.ORIGIN_Y} units lower than row * 16 so raised ground lands on 660 - 16 * n.
-->
<map version="1.10" tiledversion="1.10.2" orientation="orthogonal" renderorder="right-down" width="${cols}" height="${ROWS}" tilewidth="${TILE}" tileheight="${TILE}" infinite="0" nextlayerid="3" nextobjectid="${id}">
 <properties>
${props.join('\n')}
 </properties>
 <tileset firstgid="1" source="../ground_tileset.tsx"/>
 <layer id="1" name="ground" width="${cols}" height="${ROWS}" offsety="${T.ORIGIN_Y}">
  <data encoding="csv">
${rows.join(',\n')}
</data>
 </layer>
 <objectgroup id="2" name="entities">
${objects.join('\n')}
 </objectgroup>
</map>
`;
}

// ── read ────────────────────────────────────────────────────────────────────
function readProps(xml) {
  const out = {};
  for (const m of xml.matchAll(/<property name="([^"]+)"(?: type="[^"]*")? value="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}

function attr(s, name) {
  const m = s.match(new RegExp(`\\b${name}="([^"]*)"`));
  return m ? m[1] : undefined;
}

function read(xml) {
  const width = Number(attr(xml.match(/<map [^>]*>/)[0], 'width'));
  const csv = xml.match(/<data encoding="csv">([\s\S]*?)<\/data>/)[1];
  const grid = csv.trim().split('\n').map((r) => r.replace(/,\s*$/, '').split(',').map(Number));
  // A column's height is how far its first tile sits above the base row.
  const H = new Int8Array(width).fill(-1);
  for (let c = 0; c < width; c++) {
    for (let r = 0; r < grid.length; r++) {
      if (grid[r][c] !== 0) { H[c] = T.BASE_ROW - r; break; }
    }
  }

  const level = {
    mapWidth: width * TILE, H, grid, enemies: [], platforms: [], coins: [], artifacts: [], gates: [],
    spawnX: 0, exitX: width * TILE, props: {}, arena: null,
    generated: /name="generator"/.test(xml),
  };
  const mapProps = readProps(xml.slice(0, xml.indexOf('<tileset')));
  level.props = { era: mapProps.era, level: Number(mapProps.level), grade: Number(mapProps.grade), term: Number(mapProps.term), weeks: mapProps.weeks };

  const group = xml.slice(xml.indexOf('<objectgroup'));
  for (const m of group.matchAll(/<object\b([^>]*?)(?:\/>|>([\s\S]*?)<\/object>)/g)) {
    const a = m[1];
    const type = attr(a, 'type');
    const x = Number(attr(a, 'x'));
    const y = Number(attr(a, 'y'));
    const p = readProps(m[2] || '');
    if (type === 'boss') { level.arena = level.arena || { boss: null, minions: [] }; level.arena.boss = { x, y }; }
    else if (type === 'minion_spawn') { level.arena = level.arena || { boss: null, minions: [] }; level.arena.minions.push({ x, y }); }
    else if (type === 'spawn') level.spawnX = x;
    else if (type === 'exit') level.exitX = x;
    else if (type === 'gate') level.gates.push(x);
    else if (type === 'coin') level.coins.push({ x, y });
    else if (type === 'artifact') level.artifacts.push({ x, y, art: p.art });
    else if (type === 'platform') level.platforms.push({ x, y, width: Number(attr(a, 'width')) });
    else if (type === 'enemy') level.enemies.push({ x, y, kind: p.kind, behavior: p.behavior, patrol: Number(p.patrol) });
  }
  return level;
}

module.exports = { write, read, readProps };
